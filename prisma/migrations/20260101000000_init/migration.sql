-- LedgerLine / BalanceVault — initial PostgreSQL schema.
--
-- Applied by `prisma migrate deploy`. The Python service never creates tables in
-- Postgres; it verifies `schema_meta.version` on boot instead. SQLite keeps its
-- own schema.sql for local tests and the offline demo (see docs/DEPLOYMENT.md).
--
-- Design notes carried over from the SQLite schema:
--   * money is BIGINT minor units; no NUMERIC, no FLOAT
--   * every movement writes >= 2 ledger_entries that sum to zero
--   * ledger_entries / transactions / audit_log are append-only (trigger-enforced)
--   * accounts.balance_minor is a cache of SUM(ledger_entries.amount_minor)
--   * timestamps are ISO-8601 UTC TEXT: fixed width, so lexicographic order is
--     chronological order and the same comparisons work on both engines

CREATE TABLE users (
    id                 TEXT PRIMARY KEY,
    email              TEXT NOT NULL UNIQUE,
    full_name          TEXT NOT NULL,
    password_hash      TEXT NOT NULL,
    role               TEXT NOT NULL CHECK (role IN ('ADMIN', 'CUSTOMER', 'AUDITOR')),
    status             TEXT NOT NULL DEFAULT 'ACTIVE' CHECK (status IN ('ACTIVE', 'LOCKED', 'DISABLED')),
    failed_login_count INTEGER NOT NULL DEFAULT 0 CHECK (failed_login_count >= 0),
    locked_until       TEXT,
    created_at         TEXT NOT NULL,
    updated_at         TEXT NOT NULL
);

CREATE TABLE sessions (
    id           TEXT PRIMARY KEY,
    user_id      TEXT NOT NULL REFERENCES users(id),
    created_at   TEXT NOT NULL,
    last_used_at TEXT NOT NULL,
    revoked_at   TEXT,
    created_ip   TEXT,
    user_agent   TEXT
);
CREATE INDEX idx_sessions_user ON sessions (user_id);

CREATE TABLE refresh_tokens (
    id             TEXT PRIMARY KEY,
    user_id        TEXT NOT NULL REFERENCES users(id),
    family_id      TEXT NOT NULL,
    token_hash     TEXT NOT NULL UNIQUE,
    issued_at      TEXT NOT NULL,
    expires_at     TEXT NOT NULL,
    used_at        TEXT,
    revoked_at     TEXT,
    replaced_by_id TEXT,
    created_ip     TEXT
);
CREATE INDEX idx_refresh_tokens_user ON refresh_tokens (user_id);
CREATE INDEX idx_refresh_tokens_family ON refresh_tokens (family_id);

CREATE TABLE accounts (
    id             TEXT PRIMARY KEY,
    account_number TEXT NOT NULL UNIQUE,
    owner_user_id  TEXT REFERENCES users(id),
    name           TEXT NOT NULL,
    currency       TEXT NOT NULL CHECK (length(currency) = 3),
    balance_minor  BIGINT NOT NULL DEFAULT 0,
    is_system      SMALLINT NOT NULL DEFAULT 0 CHECK (is_system IN (0, 1)),
    status         TEXT NOT NULL DEFAULT 'ACTIVE' CHECK (status IN ('ACTIVE', 'FROZEN', 'CLOSED')),
    version        INTEGER NOT NULL DEFAULT 0 CHECK (version >= 0),
    created_at     TEXT NOT NULL,
    -- Structural guarantees: a system account has no owner, and a customer
    -- account cannot go negative even if a code path forgets to check.
    CONSTRAINT accounts_system_has_no_owner CHECK (is_system = 0 OR owner_user_id IS NULL),
    CONSTRAINT accounts_customer_non_negative CHECK (is_system = 1 OR balance_minor >= 0)
);
CREATE INDEX idx_accounts_owner ON accounts (owner_user_id);

CREATE TABLE transactions (
    id                TEXT PRIMARY KEY,
    type              TEXT NOT NULL CHECK (type IN ('DEPOSIT', 'WITHDRAWAL', 'TRANSFER')),
    currency          TEXT NOT NULL,
    amount_minor      BIGINT NOT NULL CHECK (amount_minor > 0),
    initiator_user_id TEXT REFERENCES users(id),
    description       TEXT,
    created_at        TEXT NOT NULL
);

CREATE TABLE ledger_entries (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    transaction_id TEXT NOT NULL REFERENCES transactions(id),
    account_id     TEXT NOT NULL REFERENCES accounts(id),
    amount_minor   BIGINT NOT NULL CHECK (amount_minor <> 0),
    currency       TEXT NOT NULL,
    created_at     TEXT NOT NULL,
    prev_hash      TEXT NOT NULL,
    entry_hash     TEXT NOT NULL UNIQUE
);
CREATE INDEX idx_ledger_transaction ON ledger_entries (transaction_id);
CREATE INDEX idx_ledger_account ON ledger_entries (account_id, id);

CREATE TABLE idempotency_keys (
    id              TEXT PRIMARY KEY,
    user_id         TEXT NOT NULL REFERENCES users(id),
    scope           TEXT NOT NULL,
    key             TEXT NOT NULL,
    request_hash    TEXT NOT NULL,
    response_status INTEGER NOT NULL,
    response_body   TEXT NOT NULL,
    transaction_id  TEXT,
    created_at      TEXT NOT NULL,
    CONSTRAINT idempotency_keys_scope_unique UNIQUE (user_id, scope, key)
);

CREATE TABLE audit_log (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    actor_user_id TEXT,
    actor_role    TEXT,
    subject       TEXT,
    action        TEXT NOT NULL,
    outcome       TEXT NOT NULL CHECK (outcome IN ('ALLOW', 'DENY', 'ERROR')),
    target_type   TEXT,
    target_id     TEXT,
    ip            TEXT,
    user_agent    TEXT,
    request_id    TEXT,
    detail        TEXT,
    created_at    TEXT NOT NULL,
    prev_hash     TEXT NOT NULL,
    entry_hash    TEXT NOT NULL UNIQUE
);
CREATE INDEX idx_audit_created ON audit_log (created_at);
CREATE INDEX idx_audit_action ON audit_log (action, created_at);
CREATE INDEX idx_audit_subject ON audit_log (subject, created_at);
CREATE INDEX idx_audit_ip ON audit_log (ip, created_at);

-- Append-only enforcement, same guarantee as the SQLite triggers. A compromised
-- query path still cannot rewrite history without failing loudly.
CREATE OR REPLACE FUNCTION ledgerline_forbid_mutation() RETURNS trigger AS $$
BEGIN
    RAISE EXCEPTION '% is append-only', TG_TABLE_NAME;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trg_ledger_no_update   BEFORE UPDATE ON ledger_entries FOR EACH ROW EXECUTE FUNCTION ledgerline_forbid_mutation();
CREATE TRIGGER trg_ledger_no_delete   BEFORE DELETE ON ledger_entries FOR EACH ROW EXECUTE FUNCTION ledgerline_forbid_mutation();
CREATE TRIGGER trg_tx_no_update       BEFORE UPDATE ON transactions   FOR EACH ROW EXECUTE FUNCTION ledgerline_forbid_mutation();
CREATE TRIGGER trg_tx_no_delete       BEFORE DELETE ON transactions   FOR EACH ROW EXECUTE FUNCTION ledgerline_forbid_mutation();
CREATE TRIGGER trg_audit_no_update    BEFORE UPDATE ON audit_log      FOR EACH ROW EXECUTE FUNCTION ledgerline_forbid_mutation();
CREATE TRIGGER trg_audit_no_delete    BEFORE DELETE ON audit_log      FOR EACH ROW EXECUTE FUNCTION ledgerline_forbid_mutation();

